import "dotenv/config";
import mongoose from "mongoose";
import { Pinecone } from "@pinecone-database/pinecone";
import Document from "./models/document.models.js";
import Page from "./models/page.models.js";
import Chunk from "./models/chunk.models.js";
import Fact from "./models/fact.models.js";
import ExtractionIssue from "./models/extractionIssue.models.js";
import Relationship from "./models/relationship.models.js";
await mongoose.connect(process.env.MONGO_URI);
const ids = (await Document.find({ owner: "pdfcheck" }).select("_id").lean()).map(d => d._id);
for (const M of [Fact, Chunk, Page, ExtractionIssue]) await M.deleteMany({ documentId: { $in: ids } });
await Relationship.deleteMany({ owner: "pdfcheck" });
console.log("removed pdfcheck documents:", (await Document.deleteMany({ owner: "pdfcheck" })).deletedCount);
const idx = new Pinecone({ apiKey: process.env.PINECONE_API_KEY }).index(process.env.PINECONE_INDEX_NAME);
for (const ns of ["chunks__pdfcheck", "facts__pdfcheck"]) await idx.namespace(ns).deleteAll().catch(() => {});
process.exit(0);
